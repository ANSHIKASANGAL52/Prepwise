require('dotenv').config()
const express = require('express')
const cors = require('cors')
const dns = require('dns')
const mongoose = require('mongoose')
const authRoutes = require('./routes/auth')
const sessionRoutes = require('./routes/sessions')

const app = express()
app.disable('x-powered-by')
app.use(cors({ origin: process.env.FRONTEND_URL || 'http://localhost:5173' }))
app.use(express.json({ limit: '32kb' }))
app.get('/api/health', (_req, res) => res.json({ status: 'ok', database: mongoose.connection.readyState === 1 ? 'connected' : 'disconnected' }))
app.use('/api/auth', authRoutes)
app.use('/api/sessions', sessionRoutes)
app.use((error, _req, res, _next) => res.status(500).json({ message: 'Something went wrong.', detail: error.message }))

const port = process.env.PORT || 5000
if (process.env.DNS_SERVERS) dns.setServers(process.env.DNS_SERVERS.split(',').map((server) => server.trim()).filter(Boolean))
if (process.env.MONGO_URI) mongoose.connect(process.env.MONGO_URI).then(() => console.log('MongoDB connected')).catch((error) => console.error('MongoDB connection failed:', error.message))
else console.warn('MONGO_URI is missing. The app UI will still work in local demo mode.')
app.listen(port, '0.0.0.0', () => console.log(`Prepwise API listening on ${port}`))
